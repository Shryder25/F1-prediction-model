"""Write debriefs to disk and build the static GitHub Pages site from them.

    docs/debriefs/2026-05.json   the debrief as data (source of truth for the site)
    docs/debriefs/2026-05.md     readable on GitHub, diffable in a PR
    docs/debriefs/README.md      index of every debrief

`build_site` turns every JSON file into an HTML page plus an index. It needs no
warehouse or models, so the Pages workflow runs in seconds.
"""

from __future__ import annotations

from collections.abc import Iterable
from html import escape
from pathlib import Path

from f1pred.debrief.model import Debrief
from f1pred.debrief.render import DEMO_NOTE, page, to_html, to_markdown

SITE_TITLE = "F1 post-race debriefs"


def write_debrief(d: Debrief, out_dir: Path) -> Path:
    """Save one debrief as JSON and Markdown, and refresh the Markdown index."""
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"{d.slug}.json").write_text(d.model_dump_json(indent=2) + "\n")
    path = out_dir / f"{d.slug}.md"
    path.write_text(to_markdown(d))
    (out_dir / "README.md").write_text(markdown_index(load_debriefs(out_dir)))
    return path


def load_debriefs(src_dir: Path) -> list[Debrief]:
    """Every saved debrief, newest race first."""
    debriefs = [Debrief.model_validate_json(p.read_text()) for p in src_dir.glob("*.json")]
    return sorted(debriefs, key=lambda d: (d.race.season, d.race.round), reverse=True)


def _winner(d: Debrief) -> str:
    return next((r.code for r in d.results if r.finish == 1), "?")


def markdown_index(debriefs: Iterable[Debrief]) -> str:
    lines = [
        f"# {SITE_TITLE}",
        "",
        "One report per race: predicted vs actual, strategy calls, tyre degradation and "
        "undercut outcomes. Generated by `f1pred debrief`; see "
        "[docs/debrief](../debrief/README.md) for the method.",
        "",
        "| Race | Winner | Winner predicted | Podium places right |",
        "| --- | --- | --- | --- |",
    ]
    for d in debriefs:
        demo = " (demo)" if d.race.is_demo else ""
        lines.append(
            f"| [{d.race.season} {d.race.race_name}]({d.slug}.md){demo} | {_winner(d)} | "
            f"{'yes' if d.score.winner_predicted else 'no'} | {d.score.podium_hits} of 3 |"
        )
    return "\n".join(lines) + "\n"


def build_site(src_dir: Path, out_dir: Path) -> list[Path]:
    """Render every debrief in `src_dir` to HTML in `out_dir`, plus index.html."""
    debriefs = load_debriefs(src_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for d in debriefs:
        path = out_dir / f"{d.slug}.html"
        path.write_text(to_html(d))
        written.append(path)
    (out_dir / "index.html").write_text(html_index(debriefs))
    # Pages would otherwise run Jekyll over the folder; plain HTML needs none of it.
    (out_dir / ".nojekyll").write_text("")
    return [out_dir / "index.html", *written]


def html_index(debriefs: list[Debrief]) -> str:
    rows = []
    for d in debriefs:
        s = d.score
        rows.append(
            "<tr>"
            f'<td><a href="{d.slug}.html">{d.race.season} {escape(d.race.race_name)}</a></td>'
            f"<td>{escape(d.race.race_date or '')}</td>"
            f"<td><strong>{escape(_winner(d))}</strong></td>"
            f"<td>{'yes' if s.winner_predicted else 'no'}</td>"
            f'<td class="num">{s.podium_hits} of 3</td>'
            f'<td class="num">{s.position_mae:.1f}</td>'
            "</tr>"
        )
    demo = any(d.race.is_demo for d in debriefs)
    body = (
        '<header><div class="kicker">f1pred</div>'
        f"<h1>{SITE_TITLE}</h1>"
        '<p class="meta">After every race: what the model predicted, what happened, and the '
        "strategy calls, tyre degradation and undercuts behind it.</p></header>"
        + (f'<p class="demo">{escape(DEMO_NOTE)}</p>' if demo else "")
        + (
            '<div class="scroll"><table><thead><tr><th>Race</th><th>Date</th><th>Winner</th>'
            '<th>Winner predicted</th><th class="num">Podium right</th>'
            '<th class="num">Position error</th></tr></thead><tbody>'
            + "".join(rows)
            + "</tbody></table></div>"
            if rows
            else "<p>No debriefs yet.</p>"
        )
        + '<footer><p><a href="https://github.com/Shryder25/F1-prediction-model">Source on '
        "GitHub</a></p></footer>"
    )
    return page(SITE_TITLE, body)
